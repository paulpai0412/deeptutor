const CHARACTER_PATTERN = new RegExp(
  `[${Object.keys(CHARACTER_REPLACEMENTS).join("")}]`,
  "g",
);

export function toTaiwanChinese(value: string): string {
  let result = value;
  for (const [from, to] of PHRASE_REPLACEMENTS) {
    result = result.replaceAll(from, to);
  }
  return result.replace(
    CHARACTER_PATTERN,
    (character) => CHARACTER_REPLACEMENTS[character] ?? character,
  );
}

export function taiwanizeResource<T>(value: T): T {
  if (typeof value === "string") return toTaiwanChinese(value) as T;
  if (Array.isArray(value)) {
    return value.map((item) => taiwanizeResource(item)) as T;
  }
  if (value && typeof value === "object") {
    const output: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value)) {
      output[key] = taiwanizeResource(item);
    }
    return output as T;
  }
  return value;
}
