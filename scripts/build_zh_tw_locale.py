def convert_text(text: str) -> str:
    # Apply longer phrases first.
    for src in sorted(PHRASE_OVERRIDES, key=len, reverse=True):
        text = text.replace(src, PHRASE_OVERRIDES[src])
    return text.translate(CHAR_MAP)


def convert(value):
    if isinstance(value, str):
        return convert_text(value)
    if isinstance(value, list):
        return [convert(v) for v in value]
    if isinstance(value, dict):
        return {k: convert(v) for k, v in value.items()}
    return value


def main() -> None:
    out_dir = LOCALES / "zh-TW"
    out_dir.mkdir(exist_ok=True)
    for name in ("app.json", "common.json"):
        data = json.loads((LOCALES / "zh" / name).read_text(encoding="utf-8"))
        tw = convert(data)
        tw["language.english"] = "English"
        tw["language.chinese"] = "簡體中文"
        tw["language.traditional_chinese"] = "繁體中文"
        (out_dir / name).write_text(
            json.dumps(tw, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

    for lang in ("en", "zh"):
        path = LOCALES / lang / "common.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        data.setdefault("language.traditional_chinese", "繁體中文")
        if lang == "zh":
            data["language.chinese"] = "简体中文"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    for lang in ("en", "zh"):
        path = LOCALES / lang / "app.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        data.setdefault("language.traditional_chinese", "繁體中文")
        if lang == "zh":
            data["language.chinese"] = "简体中文"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
